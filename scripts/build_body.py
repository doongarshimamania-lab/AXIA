def make_table(data, col_widths, header=True, hAlign='CENTER'):
    """Standard table with header fill + striped rows."""
    t = Table(data, colWidths=col_widths, hAlign=hAlign, repeatRows=1 if header else 0)
    style = [
        ('FONTNAME', (0, 0), (-1, -1), 'FreeSerif'),
        ('FONTSIZE', (0, 0), (-1, -1), 9.5),
        ('TEXTCOLOR', (0, 0), (-1, -1), TEXT_PRIMARY),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 7),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
        ('GRID', (0, 0), (-1, -1), 0.4, BORDER),
    ]
    if header:
        style.extend([
            ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
            ('TEXTCOLOR', (0, 0), (-1, 0), TABLE_HEADER_TEXT),
            ('FONTNAME', (0, 0), (-1, 0), 'FreeSerif-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 9.5),
            ('TOPPADDING', (0, 0), (-1, 0), 9),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 9),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [TABLE_ROW_EVEN, TABLE_ROW_ODD]),
        ])
    t.setStyle(TableStyle(style))
    return t

def make_callout(title, body_text, color=ACCENT, bg=CARD_BG):
    """CalloutBox with accent left border + light tint bg."""
    inner = Table(
        [[Paragraph(title, ParagraphStyle(name='CT', parent=callout_title_style, textColor=color))],
         [Paragraph(body_text, callout_body_style)]],
        colWidths=[AVAILABLE_WIDTH - 8],
    )
    inner.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), bg),
        ('LINEBEFORE', (0, 0), (0, -1), 3, color),
        ('TOPPADDING', (0, 0), (-1, -1), 10),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 10),
        ('LEFTPADDING', (0, 0), (-1, -1), 12),
        ('RIGHTPADDING', (0, 0), (-1, -1), 12),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
    ]))
    return KeepTogether([Spacer(1, 6), inner, Spacer(1, 10)])

