# ─── Page number footer (drawn on every body page) ────────────────────────
def draw_page_number(canvas, doc):
    """Draw 'Page N' in the footer of every body page. The body PDF starts
    at page 3 of the final merged PDF (page 1 = cover, page 2 = TOC), so
    we add +2 to the body's internal page number."""
    canvas.saveState()
    canvas.setFont('FreeSerif', 9)
    canvas.setFillColor(TEXT_MUTED)
    page_num = doc.page + 2  # +2 because cover (1) + TOC (1) precede body
    canvas.drawCentredString(PAGE_W / 2, 0.5 * inch, f'Page {page_num}')
    # Also draw a small running header on body pages (after page 1)
    if doc.page > 1:
        canvas.setFont('FreeSerif-Italic', 8)
        canvas.setFillColor(TEXT_MUTED)
        canvas.drawString(LEFT_MARGIN, PAGE_H - 0.45 * inch,
                          'Axia Client Portal — Deep Research & Implementation Blueprint')
    canvas.restoreState()

